/// q-context index from base_q_idx (matches dav1d `get_qcat_idx`).
pub(crate) fn qcat(base_q_idx: u8) -> usize {
    let q = base_q_idx as i32;
    if q <= 20 {
        0
    } else if q <= 60 {
        1
    } else if q <= 120 {
        2
    } else {
        3
    }
}

