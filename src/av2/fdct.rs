/// 1-D forward DCT-II, 16 point (avm `fwd_txfm_dct2_size16_c`). Column-strided I/O.
fn fdct16_1d(src: &[i32], dst: &mut [i32], shift: i32, line: usize) {
    let add = if shift > 0 { 1 << (shift - 1) } else { 0 };
    let m = |k: usize, c: usize| DCT16_FWD_KERNEL[k * 16 + c] as i32;
    for j in 0..line {
        let s = |k: usize| src[k * line + j];
        let mut a = [0i32; 8];
        let mut b = [0i32; 8];
        for k in 0..8 {
            a[k] = s(k) + s(15 - k);
            b[k] = s(k) - s(15 - k);
        }
        let mut c = [0i32; 4];
        let mut d = [0i32; 4];
        for k in 0..4 {
            c[k] = a[k] + a[7 - k];
            d[k] = a[k] - a[7 - k];
        }
        let e = [c[0] + c[3], c[1] + c[2]];
        let f = [c[0] - c[3], c[1] - c[2]];
        let o = &mut dst[j * 16..j * 16 + 16];
        o[0] = (m(0, 0) * e[0] + m(0, 1) * e[1] + add) >> shift;
        o[8] = (m(8, 0) * e[0] + m(8, 1) * e[1] + add) >> shift;
        o[4] = (m(4, 0) * f[0] + m(4, 1) * f[1] + add) >> shift;
        o[12] = (m(12, 0) * f[0] + m(12, 1) * f[1] + add) >> shift;
        let mut k = 2;
        while k < 16 {
            let acc: i32 = (0..4).map(|t| m(k, t) * d[t]).sum();
            o[k] = (acc + add) >> shift;
            k += 4;
        }
        let mut k = 1;
        while k < 16 {
            let acc: i32 = (0..8).map(|t| m(k, t) * b[t]).sum();
            o[k] = (acc + add) >> shift;
            k += 2;
        }
    }
}

