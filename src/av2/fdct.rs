fn fadst16_1d(src: &[i32], dst: &mut [i32], shift: i32, line: usize) {
    let add = if shift > 0 { 1 << (shift - 1) } else { 0 };
    for i in 0..line {
        let o = &mut dst[i * 16..i * 16 + 16];
        for j in 0..16 {
            let mut sum = 0i32;
            for k in 0..16 {
                sum += src[k * line + i] * ADST16_FWD_KERNEL[j * 16 + k] as i32;
            }
            o[j] = (sum + add) >> shift;
        }
    }
}

/// 2-D 16×16 forward transform with per-axis ADST/DCT (avm `fwd_txfm_c`). `col_adst`
/// = vertical pass, `row_adst` = horizontal pass. Shifts {2,11}. `[vfreq*16+hfreq]`.
pub(crate) fn fwd16x16(resid: &[i32; 256], col_adst: bool, row_adst: bool) -> [i32; 256] {
    let mut buf = [0i32; 256];
    let mut coeff = [0i32; 256];
    if col_adst {
        fadst16_1d(resid, &mut buf, 2, 16);
    } else {
        fdct16_1d(resid, &mut buf, 2, 16);
    }
    if row_adst {
        fadst16_1d(&buf, &mut coeff, 11, 16);
    } else {
        fdct16_1d(&buf, &mut coeff, 11, 16);
    }
    coeff
}

