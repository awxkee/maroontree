fn fdct64_1d(
    src: &[i32],
    dst: &mut [i32],
    shift: i32,
    line: usize,
    skip_line: usize,
    zero_line: usize,
) {
    let add = if shift > 0 { 1 << (shift - 1) } else { 0 };
    let m = |k: usize, c: usize| DCT64_FWD_KERNEL[k * 64 + c] as i32;
    let zo = zero_line != 0;
    let top = if zo { 32 } else { 64 };
    for j in 0..(line - skip_line) {
        let col = |k: usize| src[k * line + j];
        let mut a = [0i32; 32];
        let mut b = [0i32; 32];
        for k in 0..32 {
            a[k] = col(k) + col(63 - k);
            b[k] = col(k) - col(63 - k);
        }
        let mut c = [0i32; 16];
        let mut d = [0i32; 16];
        for k in 0..16 {
            c[k] = a[k] + a[31 - k];
            d[k] = a[k] - a[31 - k];
        }
        let mut e = [0i32; 8];
        let mut f = [0i32; 8];
        for k in 0..8 {
            e[k] = c[k] + c[15 - k];
            f[k] = c[k] - c[15 - k];
        }
        let mut g = [0i32; 4];
        let mut h = [0i32; 4];
        for k in 0..4 {
            g[k] = e[k] + e[7 - k];
            h[k] = e[k] - e[7 - k];
        }
        let i0 = [g[0] + g[3], g[1] + g[2]];
        let u0 = [g[0] - g[3], g[1] - g[2]];
        let o = &mut dst[j * 64..j * 64 + 64];
        o[0] = (m(0, 0) * i0[0] + m(0, 1) * i0[1] + add) >> shift;
        o[16] = (m(16, 0) * u0[0] + m(16, 1) * u0[1] + add) >> shift;
        if !zo {
            o[32] = (m(32, 0) * i0[0] + m(32, 1) * i0[1] + add) >> shift;
            o[48] = (m(48, 0) * u0[0] + m(48, 1) * u0[1] + add) >> shift;
        }
        let mut k = 8;
        while k < top {
            o[k] =
                (m(k, 0) * h[0] + m(k, 1) * h[1] + m(k, 2) * h[2] + m(k, 3) * h[3] + add) >> shift;
            k += 16;
        }
        let mut k = 4;
        while k < top {
            let acc: i32 = (0..8).map(|t| m(k, t) * f[t]).sum();
            o[k] = (acc + add) >> shift;
            k += 8;
        }
        let mut k = 2;
        while k < top {
            let acc: i32 = (0..16).map(|t| m(k, t) * d[t]).sum();
            o[k] = (acc + add) >> shift;
            k += 4;
        }
        let mut k = 1;
        while k < top {
            let acc: i32 = (0..32).map(|t| m(k, t) * b[t]).sum();
            o[k] = (acc + add) >> shift;
            k += 2;
        }
    }
}

