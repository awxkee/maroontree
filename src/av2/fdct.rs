/// 1-D forward DCT-II, 4 point (avm `fwd_txfm_dct2_size4_c`). Column-strided I/O.
fn fdct4_1d(src: &[i32], dst: &mut [i32], shift: i32, line: usize) {
    let add = if shift > 0 { 1 << (shift - 1) } else { 0 };
    let km = &DCT4_FWD_KERNEL;
    let m = |k: usize, c: usize| km[k * 4 + c] as i32;
    for j in 0..line {
        let s = |k: usize| src[k * line + j];
        let a = [s(0) + s(3), s(1) + s(2)];
        let b = [s(0) - s(3), s(1) - s(2)];
        let o = &mut dst[j * 4..j * 4 + 4];
        o[0] = (m(0, 0) * a[0] + m(0, 1) * a[1] + add) >> shift;
        o[2] = (m(2, 0) * a[0] + m(2, 1) * a[1] + add) >> shift;
        o[1] = (m(1, 0) * b[0] + m(1, 1) * b[1] + add) >> shift;
        o[3] = (m(3, 0) * b[0] + m(3, 1) * b[1] + add) >> shift;
    }
}
/// avm `fwd_tx_shift[TX_SIZE]` — (shift_1st for col/height pass, shift_2nd for row/width pass).
pub(crate) fn fwd_shifts(w: usize, h: usize) -> (i32, i32) {
    match (w, h) {
        (4, 4) => (1, 10),
        (8, 8) => (2, 10),
        (16, 16) => (2, 11),
        (32, 32) => (3, 12),
        (64, 64) => (3, 14),
        (4, 8) => (1, 11),
        (8, 4) => (1, 11),
        (8, 16) => (1, 12),
        (16, 8) => (2, 11),
        (16, 32) => (2, 13),
        (32, 16) => (3, 12),
        (32, 64) => (3, 14),
        (64, 32) => (3, 14),
        (4, 16) => (1, 11),
        (16, 4) => (1, 11),
        (8, 32) => (1, 12),
        (32, 8) => (3, 10),
        (16, 64) => (2, 13),
        (64, 16) => (3, 12),
        (4, 32) => (1, 12),
        (32, 4) => (1, 12),
        (8, 64) => (2, 13),
        (64, 8) => (4, 11),
        (4, 64) => (1, 12),
        (64, 4) => (1, 12),
        _ => unreachable!("unsupported tx {w}x{h}"),
    }
}

/// avm DC tx-scale exponent: factor applied at dequant is `2^(3 + dc_tx_scale)`.
pub(crate) fn dc_tx_scale(w: usize, h: usize) -> u32 {
    let s = w.trailing_zeros() + h.trailing_zeros();
    if s <= 8 { 0 } else { (s - 7) / 2 }
}

fn fdct_1d_n(n: usize, src: &[i32], dst: &mut [i32], shift: i32, line: usize, zero: usize) {
    match n {
        4 => fdct4_1d(src, dst, shift, line),
        8 => fdct8_1d(src, dst, shift, line),
        16 => fdct16_1d(src, dst, shift, line),
        32 => fdct32_1d(src, dst, shift, line),
        64 => fdct64_1d(src, dst, shift, line, 0, zero),
        _ => unreachable!("unsupported 1D size {n}"),
    }
}

struct PassScratch {
    buf: Box<[i32; 4096]>,
    coeff: Box<[i32; 4096]>,
}

thread_local! {
    static PASS_SCRATCH: RefCell<PassScratch> =
        RefCell::new(PassScratch { buf: Box::new([0; 4096]), coeff: Box::new([0; 4096]) });
}

pub(crate) type FdctRectFn = unsafe fn(&[i32], usize, usize, &mut [i32]) -> usize;

static FDCT_RECT: OnceLock<FdctRectFn> = OnceLock::new();

unsafe fn fdct_rect_scalar(resid: &[i32], w: usize, h: usize, out: &mut [i32]) -> usize {
    let (s1, s2) = fwd_shifts(w, h);
    let zh = if h > 32 { 32 } else { 0 };
    let zw = if w > 32 { 32 } else { 0 };
    let (cw, ch) = (w.min(32), h.min(32));
    PASS_SCRATCH.with(|cell| {
        let s = &mut *cell.borrow_mut();
        fdct_1d_n(h, resid, &mut s.buf[..w * h], s1, w, zh); // col pass (height)
        fdct_1d_n(w, &s.buf[..w * h], &mut s.coeff[..w * h], s2, h, zw); // row pass (width)
        for vf in 0..ch {
            for hf in 0..cw {
                out[vf * cw + hf] = s.coeff[vf * w + hf];
            }
        }
    });
    if (w.trailing_zeros() + h.trailing_zeros()) & 1 == 1 {
        for v in out[..cw * ch].iter_mut() {
            *v = (((*v as i64) * 5793 + 2048) >> 12) as i32;
        }
    }
    cw * ch
}

#[inline]
fn resolve_fdct_rect() -> FdctRectFn {
    *FDCT_RECT.get_or_init(|| {
        let mut _f = fdct_rect_scalar as FdctRectFn;
        #[cfg(all(target_arch = "aarch64", feature = "neon"))]
        {
            _f = crate::av2::neon::fdct_rect_neon as FdctRectFn;
        }
        #[cfg(all(any(target_arch = "x86", target_arch = "x86_64"), feature = "avx"))]
        {
            if std::is_x86_feature_detected!("avx2") {
                _f = crate::av2::avx::fdct_rect_avx2 as FdctRectFn;
            }
        }
        _f
    })
}

pub(crate) fn fdct_rect(resid: &[i32], w: usize, h: usize, out: &mut [i32]) -> usize {
    let f = resolve_fdct_rect();
    unsafe { f(resid, w, h, out) }
}

