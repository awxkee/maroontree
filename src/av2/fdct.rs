/// 1-D forward DCT-II, 32 point (avm `fwd_txfm_dct2_size32_c`).
///
/// Transforms `line` independent length-32 vectors. Input is column-strided:
/// element `k` of vector `j` is `src[k*line + j]`. Output vector `j` is written
/// contiguously at `dst[j*32 ..][freq]`. `shift` rounds and downscales.
fn fdct32_1d(src: &[i32], dst: &mut [i32], shift: i32, line: usize) {
    debug_assert!(shift > 0);
    let add = 1 << (shift - 1);
    // kernel row `k`, column `col`
    let m = |k: usize, col: usize| DCT32_FWD_KERNEL[k * 32 + col] as i32;

    for j in 0..line {
        let col = |k: usize| src[k * line + j];

        // Even/odd butterfly fold, then fold the even half down to g/h.
        let mut a = [0i32; 16];
        let mut b = [0i32; 16];
        for k in 0..16 {
            a[k] = col(k) + col(31 - k);
            b[k] = col(k) - col(31 - k);
        }
        let mut c = [0i32; 8];
        let mut d = [0i32; 8];
        for k in 0..8 {
            c[k] = a[k] + a[15 - k];
            d[k] = a[k] - a[15 - k];
        }
        let mut e = [0i32; 4];
        let mut f = [0i32; 4];
        for k in 0..4 {
            e[k] = c[k] + c[7 - k];
            f[k] = c[k] - c[7 - k];
        }
        let g = [e[0] + e[3], e[1] + e[2]];
        let h = [e[0] - e[3], e[1] - e[2]];

        let o = &mut dst[j * 32..j * 32 + 32];
        // Even-even frequencies from g (rows 0,16) and h (rows 8,24): 2 taps each.
        o[0] = (m(0, 0) * g[0] + m(0, 1) * g[1] + add) >> shift;
        o[16] = (m(16, 0) * g[0] + m(16, 1) * g[1] + add) >> shift;
        o[8] = (m(8, 0) * h[0] + m(8, 1) * h[1] + add) >> shift;
        o[24] = (m(24, 0) * h[0] + m(24, 1) * h[1] + add) >> shift;
        // Rows 4,12,20,28 from f: 4 taps.
        for k in (4..32).step_by(8) {
            let acc = (0..4).map(|i| m(k, i) * f[i]).sum::<i32>();
            o[k] = (acc + add) >> shift;
        }
        // Rows 2,6,10,… from d: 8 taps.
        for k in (2..32).step_by(4) {
            let acc = (0..8).map(|i| m(k, i) * d[i]).sum::<i32>();
            o[k] = (acc + add) >> shift;
        }
        // Odd rows from b: 16 taps.
        for k in (1..32).step_by(2) {
            let acc = (0..16).map(|i| m(k, i) * b[i]).sum::<i32>();
            o[k] = (acc + add) >> shift;
        }
    }
}

